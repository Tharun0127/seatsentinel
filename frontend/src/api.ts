// Typed wrappers around the SeatSentinel API. Everything goes through /api,
// which the Vite dev server or nginx forwards to FastAPI.

export type EventSummary = {
  id: number;
  name: string;
  venue: string;
  starts_at: string;
  seats_total: number;
  seats_booked: number;
};

export type SeatState = "free" | "held" | "booked";

export type Seat = {
  id: number;
  row_label: string;
  number: number;
  price: string;
  state: SeatState;
  mine: boolean;
  hold_expires_in_ms: number | null;
};

export type Payment = { payment_id: string; amount: string; seat_ids: number[]; event_id: number };

export type Confirmation = {
  reference: string;
  seat_ids: number[];
  amount: string;
  late_hold_recovered: boolean;
};

export type MyBooking = {
  reference: string;
  event_name: string;
  starts_at: string;
  booked_at: string;
  seats: string[];
  amount: string;
  strategy: string;
};

export class ApiError extends Error {
  constructor(public status: number, message: string) {
    super(message);
  }
}

const TOKEN_KEY = "seatsentinel.token";

export function getToken(): string | null {
  try {
    return localStorage.getItem(TOKEN_KEY);
  } catch {
    return null;
  }
}

export function setToken(token: string | null) {
  try {
    if (token) localStorage.setItem(TOKEN_KEY, token);
    else localStorage.removeItem(TOKEN_KEY);
  } catch {
    // Storage blocked (private mode): the user just has to log in again.
  }
}

async function request<T>(method: string, path: string, body?: unknown, extraHeaders?: Record<string, string>) {
  const headers: Record<string, string> = { "Content-Type": "application/json", ...extraHeaders };
  const token = getToken();
  if (token) headers.Authorization = `Bearer ${token}`;
  const response = await fetch(`/api${path}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) {
    const detail = typeof data.detail === "string" ? data.detail : "Something went wrong";
    if (response.status === 401) setToken(null);
    throw new ApiError(response.status, detail);
  }
  return data as T;
}

export const api = {
  login: (email: string, password: string) =>
    request<{ access_token: string; email: string }>("POST", "/auth/login", { email, password }),
  signup: (email: string, password: string) =>
    request<{ access_token: string; email: string }>("POST", "/auth/signup", { email, password }),
  events: () => request<EventSummary[]>("GET", "/events"),
  seats: (eventId: number) => request<Seat[]>("GET", `/events/${eventId}/seats`),
  hold: (eventId: number, seatIds: number[]) =>
    request<{ seat_ids: number[]; expires_in_ms: number }>("POST", `/events/${eventId}/holds`, { seat_ids: seatIds }),
  release: (eventId: number, seatIds: number[]) =>
    request<{ released: number }>("DELETE", `/events/${eventId}/holds`, { seat_ids: seatIds }),
  // The Idempotency-Key is generated by the caller and REUSED on retry, so a
  // retried click can never charge or book twice.
  pay: (eventId: number, seatIds: number[], cardLast4: string, idempotencyKey: string) =>
    request<Payment>(
      "POST",
      "/payments",
      { event_id: eventId, seat_ids: seatIds, card_last4: cardLast4 },
      { "Idempotency-Key": idempotencyKey },
    ),
  confirm: (paymentId: string, idempotencyKey: string) =>
    request<Confirmation>("POST", "/bookings/confirm", { payment_id: paymentId }, { "Idempotency-Key": idempotencyKey }),
  myBookings: () => request<MyBooking[]>("GET", "/bookings/me"),
};
